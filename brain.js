/* =====================================================================
   COMUNIDADE PERFORMANCE — brain.js
   =====================================================================
   Used ONLY by brain.html. Three tools:
     1. Pomodoro timer
     2. Reading calculator
     3. Breathing exercise
   Everything runs in the visitor's browser. Nothing is saved (a reload
   resets the tools) and nothing is sent anywhere.
   ===================================================================== */

"use strict";

/* Shared little helpers */
const pad2 = (n) => String(n).padStart(2, "0");
// Reads a number from a field; accepts "10,5" or "10.5". Invalid = 0.
const readNum = (input) => {
  const value = parseFloat(String(input.value).replace(",", "."));
  return Number.isFinite(value) && value > 0 ? value : 0;
};


/* ---------------------------------------------------------------------
   1. POMODORO TIMER
   - Default durations come from the inputs in brain.html (value="25"...).
   - Phase names shown on screen: change LABELS below.
   - Keeps correct time in the background: it stores the END TIME and
     compares with the clock, instead of counting seconds.
   - Sound is generated by the browser (no audio file, no download).
   - "Manter a tela ligada" uses the Screen Wake Lock API when the
     phone/browser supports it (silently ignored otherwise).
   --------------------------------------------------------------------- */
(function pomodoro() {
  const root = document.querySelector("[data-pomo]");
  if (!root) return;

  const LABELS = { focus: "foco", short: "pausa curta", long: "pausa longa" };

  const $ = (sel) => document.querySelector(sel);
  const clock = $("[data-pomo-clock]");
  const status = $("[data-pomo-status]");
  const ring = $("[data-pomo-ring]");
  const dots = $("[data-pomo-dots]");
  const announce = $("[data-pomo-announce]");
  const startBtn = $("[data-pomo-start]");
  const resetBtn = $("[data-pomo-reset]");
  const skipBtn = $("[data-pomo-skip]");
  const inputs = {
    focus: $("#pomo-focus"), short: $("#pomo-short"), long: $("#pomo-long"),
    every: $("#pomo-every"),
  };
  const opt = {
    auto: $("#pomo-auto"), sound: $("#pomo-sound"),
    vibrate: $("#pomo-vibrate"), wake: $("#pomo-wake"),
  };

  const baseTitle = document.title;

  let mode = "focus";
  let total = minutesOf("focus") * 60000; // phase length in ms
  let remaining = total;                  // ms left
  let endAt = 0;                          // clock time when phase ends
  let running = false;
  let timer = null;
  let done = 0;                           // focus sessions in this round
  let wakeLock = null;
  let audio = null;

  function minutesOf(m) {
    const max = m === "focus" ? 180 : 60;
    return Math.min(max, Math.max(1, Math.round(readNum(inputs[m]) || 1)));
  }
  const every = () => Math.min(12, Math.max(2, Math.round(readNum(inputs.every) || 4)));

  const fmt = (ms) => {
    const sec = Math.ceil(ms / 1000);
    return `${pad2(Math.floor(sec / 60))}:${pad2(sec % 60)}`;
  };

  // ---------- Screen ----------
  function render() {
    const time = fmt(remaining);
    clock.textContent = time;
    ring.style.strokeDashoffset = String(100 * (1 - remaining / total));

    const started = remaining < total;
    status.textContent = `${LABELS[mode]} · ${running ? "rodando" : started ? "pausado" : "pronto"}`;
    startBtn.textContent = running ? "Pausar" : started ? "Continuar" : "Iniciar";

    // Browser tab shows the time while a phase is in progress
    document.title = running || started ? `${time} · ${LABELS[mode]} — ${baseTitle}` : baseTitle;

    // One square per pomodoro of the round
    const n = every();
    if (dots.children.length !== n) {
      dots.replaceChildren(...Array.from({ length: n }, () => document.createElement("span")));
    }
    [...dots.children].forEach((dot, i) => dot.classList.toggle("is-done", i < done));
  }

  // ---------- Sound / vibration / screen ----------
  function unlockAudio() {
    // Browsers only allow sound after a click, so we prepare it here.
    const AudioCtx = window.AudioContext || window.webkitAudioContext;
    if (!audio && AudioCtx) audio = new AudioCtx();
    if (audio && audio.state === "suspended") audio.resume();
  }

  function beep() {
    if (!opt.sound.checked || !audio) return;
    const t = audio.currentTime;
    [0, 0.3, 0.6].forEach((delay) => {
      const osc = audio.createOscillator();
      const gain = audio.createGain();
      osc.frequency.value = 880; // tone (Hz)
      osc.connect(gain);
      gain.connect(audio.destination);
      gain.gain.setValueAtTime(0.0001, t + delay);
      gain.gain.exponentialRampToValueAtTime(0.3, t + delay + 0.02);
      gain.gain.exponentialRampToValueAtTime(0.0001, t + delay + 0.22);
      osc.start(t + delay);
      osc.stop(t + delay + 0.25);
    });
  }

  function vibrate() {
    if (opt.vibrate.checked && navigator.vibrate) navigator.vibrate([200, 100, 200]);
  }

  async function keepScreenOn() {
    if (!opt.wake.checked || !("wakeLock" in navigator) || wakeLock) return;
    try {
      wakeLock = await navigator.wakeLock.request("screen");
      wakeLock.addEventListener("release", () => { wakeLock = null; });
    } catch (error) { /* not allowed now (e.g. battery saver) — ignore */ }
  }

  function releaseScreen() {
    if (wakeLock) wakeLock.release().catch(() => {});
    wakeLock = null;
  }

  // ---------- Timer ----------
  function tick() {
    remaining = Math.max(0, endAt - Date.now());
    if (remaining <= 0) finish();
    else render();
  }

  function start() {
    unlockAudio();
    running = true;
    endAt = Date.now() + remaining;
    clearInterval(timer);
    timer = setInterval(tick, 250);
    keepScreenOn();
    render();
  }

  function pause() {
    running = false;
    clearInterval(timer);
    remaining = Math.max(0, endAt - Date.now());
    releaseScreen();
    render();
  }

  // Switch phase (focus / short / long). autoStart = start right away.
  function setMode(next, autoStart) {
    clearInterval(timer);
    running = false;
    mode = next;
    total = remaining = minutesOf(next) * 60000;
    const radio = root.querySelector(`input[name="pomo-mode"][value="${next}"]`);
    if (radio) radio.checked = true;
    if (autoStart) start();
    else { releaseScreen(); render(); }
  }

  // Picks what comes after the current phase.
  function nextMode(countIt) {
    if (mode === "focus") {
      if (countIt) done += 1;
      return done >= every() ? "long" : "short";
    }
    if (mode === "long") done = 0; // round complete
    return "focus";
  }

  function finish() {
    clearInterval(timer);
    running = false;
    remaining = 0;
    render();
    beep();
    vibrate();
    const ended = LABELS[mode];
    const next = nextMode(true);
    announce.textContent = `${ended} terminado. Agora: ${LABELS[next]}.`;
    setMode(next, opt.auto.checked);
  }

  // ---------- Buttons and settings ----------
  startBtn.addEventListener("click", () => (running ? pause() : start()));
  resetBtn.addEventListener("click", () => setMode(mode, false));
  skipBtn.addEventListener("click", () => setMode(nextMode(false), false));

  root.addEventListener("change", (event) => {
    if (event.target.name === "pomo-mode") setMode(event.target.value, false);
  });

  // Changing a duration applies it right away if that phase hasn't started.
  Object.values(inputs).forEach((input) => input.addEventListener("input", () => {
    if (!running && remaining === total) setMode(mode, false);
    else render();
  }));

  opt.wake.addEventListener("change", () => {
    if (opt.wake.checked && running) keepScreenOn(); else releaseScreen();
  });

  // Coming back to the tab: update now and turn the screen lock back on.
  document.addEventListener("visibilitychange", () => {
    if (document.visibilityState === "visible" && running) { tick(); keepScreenOn(); }
  });

  render();
})();


/* ---------------------------------------------------------------------
   2. READING CALCULATOR
   pages per hour (pph) = your pace
     or, in words:   pph = words per minute x 60 / words per page
   pages in your time   = pph x minutes / 60
   SAFE TO CHANGE: READING_SIMULATIONS (minutes per day in the table).
   --------------------------------------------------------------------- */
const READING_SIMULATIONS = [10, 15, 20, 30, 45, 60, 90, 120];

(function readingCalculator() {
  const root = document.querySelector("[data-read]");
  if (!root) return;

  const $ = (sel) => document.querySelector(sel);
  const f = {
    pph: $("#read-pph"), wpm: $("#read-wpm"), wpp: $("#read-wpp"),
    h: $("#read-h"), min: $("#read-min"), book: $("#read-book"),
    testPages: $("#read-test-pages"), testMin: $("#read-test-min"),
  };
  const pphField = $("[data-read-pph-field]");
  const wpmField = $("[data-read-wpm-field]");
  const msg = $("[data-read-msg]");
  const out = (name) => $(`[data-read-out="${name}"]`);

  const nf0 = new Intl.NumberFormat("pt-BR", { maximumFractionDigits: 0 });
  const nf1 = new Intl.NumberFormat("pt-BR", { maximumFractionDigits: 1 });

  const unit = () => root.querySelector('input[name="read-unit"]:checked').value;

  // 30 -> "30 min"   |   90 -> "1h30"
  function fmtMinutes(min) {
    const total = Math.round(min);
    if (total < 60) return `${total} min`;
    return `${Math.floor(total / 60)}h${pad2(total % 60)}`;
  }

  // Pages: 1 decimal for small numbers, whole number above 10
  const fmtPages = (p) => (p < 10 ? nf1.format(p) : nf0.format(p));

  function showUnitFields() {
    const words = unit() === "wpm";
    pphField.hidden = words;
    wpmField.hidden = !words;
  }

  function clear(text) {
    msg.textContent = text;
    out("pages").textContent = "—";
    out("summary").textContent = "";
    ["book-time", "book-days", "month", "year"].forEach((n) => { out(n).textContent = "—"; });
    out("table").replaceChildren();
  }

  function calc() {
    const pph = unit() === "pph"
      ? readNum(f.pph)
      : (readNum(f.wpm) * 60) / Math.max(1, readNum(f.wpp));
    const minutes = readNum(f.h) * 60 + readNum(f.min);
    const book = readNum(f.book);

    if (!(pph > 0)) return clear("Informe seu ritmo de leitura.");
    if (!(minutes > 0)) return clear("Informe o tempo de leitura.");
    msg.textContent = "";

    const pages = (pph * minutes) / 60;

    out("label").textContent = `em ${fmtMinutes(minutes)} você lê`;
    const small = document.createElement("small");
    small.textContent = pages === 1 ? "página" : "páginas";
    out("pages").replaceChildren(fmtPages(pages), small);
    out("summary").textContent = `no ritmo de ${nf1.format(pph)} páginas por hora`;

    if (book > 0) {
      out("book-time").textContent = fmtMinutes((book / pph) * 60);
      out("book-days").textContent = nf0.format(Math.ceil(book / pages));
      out("month").textContent = nf1.format((pages * 30) / book);
      out("year").textContent = nf1.format((pages * 365) / book);
      out("table-title").textContent = `simulacoes/ livro de ${nf0.format(book)} páginas`;
    } else {
      ["book-time", "book-days", "month", "year"].forEach((n) => { out(n).textContent = "—"; });
    }

    // Simulation table (your time is added and highlighted)
    const times = [...new Set([...READING_SIMULATIONS, Math.round(minutes)])].sort((a, b) => a - b);
    out("table").replaceChildren(...times.map((t) => {
      const p = (pph * t) / 60;
      const tr = document.createElement("tr");
      if (t === Math.round(minutes)) tr.className = "is-current";
      const cells = [
        fmtMinutes(t),
        fmtPages(p),
        book > 0 ? nf0.format(Math.ceil(book / p)) : "—",
        book > 0 ? nf1.format((p * 365) / book) : "—",
      ];
      cells.forEach((value, i) => {
        const td = document.createElement("td");
        td.textContent = value;
        if (i > 0) td.className = "num";
        tr.append(td);
      });
      return tr;
    }));
  }

  // ---------- Events ----------
  root.addEventListener("input", calc);
  root.addEventListener("change", (event) => {
    if (event.target.name === "read-unit") { showUnitFields(); calc(); }
  });

  // Quick time buttons (15 min, 30 min, 1 h, 2 h)
  root.querySelectorAll("[data-min]").forEach((chip) => chip.addEventListener("click", () => {
    const total = Number(chip.dataset.min);
    f.h.value = Math.floor(total / 60);
    f.min.value = total % 60;
    calc();
  }));

  // "Não sei meu ritmo": pages read in X minutes -> pages per hour
  $("[data-read-measure]").addEventListener("click", () => {
    const pages = readNum(f.testPages);
    const min = readNum(f.testMin);
    if (!(pages > 0 && min > 0)) { msg.textContent = "Preencha páginas e minutos do teste."; return; }
    root.querySelector('input[name="read-unit"][value="pph"]').checked = true;
    showUnitFields();
    f.pph.value = nf1.format((pages / min) * 60);
    calc();
    f.pph.focus();
  });

  showUnitFields();
  calc();
})();


/* ---------------------------------------------------------------------
   3. BREATHING EXERCISE (box breathing)
   4 phases of PHASE_MS milliseconds each.
   SAFE TO CHANGE: the labels and PHASE_MS (if you change PHASE_MS, also
   change the "4s" transition of .breath-circle in styles.css).
   --------------------------------------------------------------------- */
(function breathing() {
  const root = document.querySelector("[data-breath]");
  if (!root) return;

  const circle = root.querySelector("[data-breath-circle]");
  const label = root.querySelector("[data-breath-label]");
  const toggle = document.querySelector("[data-breath-toggle]");
  if (!circle || !label || !toggle) return;

  const PHASE_MS = 4000;
  const PHASES = [
    { text: "inspire…", expand: true },
    { text: "segure…",  expand: true },
    { text: "expire…",  expand: false },
    { text: "segure…",  expand: false },
  ];

  let timer = null;
  let step = 0;

  function runPhase() {
    const phase = PHASES[step % PHASES.length];
    label.textContent = phase.text;
    circle.classList.toggle("is-in", phase.expand);
    step += 1;
  }

  function start() {
    step = 0;
    runPhase();
    timer = setInterval(runPhase, PHASE_MS);
    toggle.textContent = "Parar";
  }

  function stop() {
    clearInterval(timer);
    timer = null;
    circle.classList.remove("is-in");
    label.textContent = "pronto?";
    toggle.textContent = "Iniciar";
  }

  toggle.addEventListener("click", () => (timer ? stop() : start()));
})();
